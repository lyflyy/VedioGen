import { chromium, expect } from "@playwright/test";
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

// Opt-in: edits the selected engineering project's storyboard through the UI.
const projectId = process.env.NARRATION_TEST_PROJECT;
const clip = process.env.NARRATION_TEST_CLIP;
const voice = process.env.NARRATION_TEST_VOICE;
if (!projectId || !clip || !voice) throw new Error("Set NARRATION_TEST_PROJECT, NARRATION_TEST_CLIP and NARRATION_TEST_VOICE for an engineering project.");
const baseURL = process.env.NARRATION_TEST_ORIGIN || "http://127.0.0.1:3001";
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(baseURL)) throw new Error("Local origin required");
const directory = path.resolve(".data/internal-mvp/narration-evidence");
await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
page.setDefaultTimeout(30_000);
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
try {
  await page.goto(`${baseURL}/admin/video-settings`);
  await page.getByLabel("中文声音模型路径").fill(voice);
  await page.getByLabel("启用本地 Piper 旁白").check();
  const saved = page.waitForResponse((r) => r.url().endsWith("/admin/video-settings") && r.request().method() === "PUT");
  await page.getByRole("button", { name: "保存视频配置" }).click();
  const saveResponse = await saved;
  if (!saveResponse.ok()) throw new Error(await saveResponse.text());
  await page.reload();
  await expect(page.getByLabel("启用本地 Piper 旁白")).toBeChecked();
  await expect(page.getByLabel("中文声音模型路径")).toHaveValue(voice);
  await page.screenshot({ path: path.join(directory, "admin-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(directory, "admin-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${baseURL}/projects/${projectId}/storyboard`);
  const workspace = await page.request.get(`${baseURL}/api/v1/projects/${projectId}/workspace`);
  await writeFile(path.join(directory, "workspace-before.json"), await workspace.text());
  const uploaded = page.waitForResponse((r) => r.status() === 201 && r.request().method() === "PUT" && r.url().includes("/assets/"));
  await page.locator('input[type="file"][accept="image/*,video/*,audio/*"]').setInputFiles(path.resolve(clip));
  await uploaded;
  await expect(page.getByRole("combobox", { name: "来源", exact: true })).toBeEnabled();
  const refreshed = await (await page.request.get(`${baseURL}/api/v1/projects/${projectId}/workspace`)).json();
  const asset = refreshed.assetVersions.find((item) => item.kind === "video" && item.fileName === path.basename(clip));
  if (!asset) throw new Error("Uploaded clip not found in project assets");
  await page.getByRole("combobox", { name: "来源", exact: true }).selectOption("user-video");
  await expect(page.getByLabel("镜头素材").locator(`option[value="${asset.id}"]`)).toBeAttached();
  await page.getByLabel("镜头素材").selectOption(asset.id);
  await page.getByLabel("旁白", { exact: true }).fill("春风八百，穿越山林。");
  await page.getByLabel("字幕", { exact: true }).fill("春风八百，穿越山林");
  const storyboardSaved = page.waitForResponse((r) => r.url().includes("/storyboards/") && r.request().method() === "PUT");
  await page.getByRole("button", { name: "保存分镜", exact: true }).click();
  if (!(await storyboardSaved).ok()) throw new Error("Storyboard save failed");
  await page.getByRole("button", { name: "确认分镜", exact: true }).click();
  await page.waitForURL("**/generation");
  await page.getByLabel("输出尺寸").selectOption("preview");
  await page.getByLabel("生成本地中文旁白").check();
  await page.screenshot({ path: path.join(directory, "generation-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(directory, "generation-mobile.png"), fullPage: true });
  const started = page.waitForResponse((r) => r.url().endsWith("/generation-runs") && r.request().method() === "POST");
  await page.getByRole("button", { name: /^(按当前分镜生成|开始生成)$/ }).click();
  const response = await started;
  const initialRun = await response.json();
  if (response.status() !== 202) throw new Error(JSON.stringify(initialRun));
  let run;
  await expect.poll(async () => {
    run = await (await page.request.get(`${baseURL}/api/v1/generation-runs/${initialRun.id}`)).json();
    return ["completed", "failed", "interrupted", "cancelled"].includes(run.status);
  }, { timeout: 120_000, intervals: [1000] }).toBe(true);
  if (run.status !== "completed") throw new Error(JSON.stringify(run));
  expect(run.audioMode).toBe("local-narration");
  await page.getByRole("link", { name: "查看成片" }).click();
  await expect(page.getByText("本地中文旁白与素材原声混合", { exact: true })).toBeVisible();
  const video = page.locator("video").first();
  await expect.poll(() => video.evaluate((v) => v.readyState)).toBeGreaterThanOrEqual(2);
  await video.evaluate(async (v) => { v.muted = true; await v.play(); });
  await expect.poll(() => video.evaluate((v) => v.currentTime)).toBeGreaterThan(0.4);
  const pixels = await video.evaluate((v) => {
    const canvas = document.createElement("canvas");
    canvas.width = 64; canvas.height = 64;
    const ctx = canvas.getContext("2d");
    ctx.drawImage(v, 0, 0, 64, 64);
    return new Set(ctx.getImageData(0, 0, 64, 64).data).size;
  });
  expect(pixels).toBeGreaterThan(30);
  await page.screenshot({ path: path.join(directory, "final-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: path.join(directory, "final-desktop.png"), fullPage: true });
  const downloaded = page.waitForEvent("download");
  await page.getByRole("link", { name: /下载/ }).click();
  const download = await downloaded;
  await download.saveAs(path.join(directory, "final.mp4"));
  const content = await (await page.request.get(`${baseURL}/api/v1/artifacts/${run.finalArtifactId}/content`)).body();
  const evidence = { projectId, run, sourceAssetId: asset.id, downloadSha256: createHash("sha256").update(content).digest("hex"), pixels, errors };
  await writeFile(path.join(directory, "result.json"), JSON.stringify(evidence, null, 2));
  expect(errors).toEqual([]);
  console.log(JSON.stringify(evidence, null, 2));
} catch (error) {
  await page.screenshot({ path: path.join(directory, "failure.png"), fullPage: true });
  throw error;
} finally {
  await browser.close();
}
